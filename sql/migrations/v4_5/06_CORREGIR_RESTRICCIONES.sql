-- Correcciones verificadas: contacto opcional y catalogos tecnicos requeridos por la inscripcion.
SET NOCOUNT ON;SET XACT_ABORT ON;
DECLARE @BaseEsperada sysname=N'FractalesAcademy';
IF DB_NAME()<>@BaseEsperada THROW 54500,'Confirma base y servidor.',1;
IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WHERE SCRIPT='V45_05_AUDITORIA') THROW 54501,'Falta 05.',1;
BEGIN TRY BEGIN TRAN;
IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WITH(UPDLOCK,HOLDLOCK) WHERE SCRIPT='V45_06_RESTRICCIONES')
BEGIN
 -- Conserva DNI varchar(8), celulares varchar(9), identificadores y relaciones.
 IF EXISTS(SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('dbo.ALUMNO') AND name IN('NOMBRE_APODERADO','ID_PARENTESCO') AND is_nullable=0)
  THROW 54506,'Contacto no opcional: revisar migracion V4.4 y diagnostico. No se eliminan controles desconocidos.',1;
 IF NOT EXISTS(SELECT 1 FROM dbo.ROL WHERE ID_ROL='ALUMNO') OR NOT EXISTS(SELECT 1 FROM dbo.ESTADO_MATRICULA WHERE ID_ESTADO_MATRICULA='ACTIVA') OR NOT EXISTS(SELECT 1 FROM dbo.ESTADO_PAGO WHERE ID_ESTADO_PAGO='PENDIENTE')
  THROW 54506,'Catalogos de rol/estados incompletos; revisar antes de crear datos.',1;
 IF NOT EXISTS(SELECT 1 FROM dbo.CONCEPTO_PAGO WHERE ID_CONCEPTO='MENSUALIDAD')
  INSERT dbo.CONCEPTO_PAGO(ID_CONCEPTO,NOMBRE_CONCEPTO) VALUES('MENSUALIDAD','Mensualidad');
 IF NOT EXISTS(SELECT 1 FROM dbo.CONCEPTO_PAGO WHERE ID_CONCEPTO='MATRICULA_INICIAL')
  INSERT dbo.CONCEPTO_PAGO(ID_CONCEPTO,NOMBRE_CONCEPTO) VALUES('MATRICULA_INICIAL','Matricula y materiales');
 -- Registrar unicamente altas tecnicas aprobadas para que 07 distinga incorporacion de perdida.
 INSERT dbo.MIGRACION_INTEGRIDAD_V45(TABLA,CLAVE,HUELLA)
 SELECT 'CONCEPTO_PAGO',(SELECT r.ID_CONCEPTO FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES),
 HASHBYTES('SHA2_256',(SELECT r.ID_CONCEPTO,r.NOMBRE_CONCEPTO FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES))
 FROM dbo.CONCEPTO_PAGO r WHERE r.ID_CONCEPTO IN('MENSUALIDAD','MATRICULA_INICIAL') AND NOT EXISTS(SELECT 1 FROM dbo.MIGRACION_INTEGRIDAD_V45 b WHERE b.TABLA='CONCEPTO_PAGO' AND b.CLAVE=(SELECT r.ID_CONCEPTO FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES));
 INSERT dbo.CONTROL_MIGRACION(SCRIPT) VALUES('V45_06_RESTRICCIONES');
END; COMMIT;
END TRY BEGIN CATCH IF XACT_STATE()<>0 ROLLBACK;THROW;END CATCH;
