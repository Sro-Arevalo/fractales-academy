-- FRACTALES ACADEMY V4.5 | RECONCILIACION CONTROLADA DEL CATALOGO
-- SOLO EJECUTAR SI 00 DIAGNOSTICO:
-- 1) marca PENDIENTE como la UNICA alta posterior a la linea base;
-- 2) marca todos los estados anteriores como COINCIDE;
-- 3) no muestra claves antiguas ausentes;
-- 4) la base dispone de respaldo recuperable y no hay escrituras concurrentes.
-- No cambia ESTADO_PAGO; no altera huellas existentes; solo documenta
-- el alta aprobada de PENDIENTE dentro de MIGRACION_INTEGRIDAD_V45.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF DB_NAME()<>N'FractalesAcademy'
  THROW 54701, 'Base distinta de FractalesAcademy.',1;
IF OBJECT_ID(N'dbo.MIGRACION_INTEGRIDAD_V45',N'U') IS NULL
  THROW 54702,'No existe la linea base de V4.5.',1;
IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WHERE SCRIPT=N'V45_06_RESTRICCIONES')
  THROW 54703,'La migracion 06 no esta registrada.',1;
IF EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WHERE SCRIPT=N'V45_08_FINALIZAR')
  THROW 54704,'La migracion 08 ya fue ejecutada.',1;
BEGIN TRY
  BEGIN TRANSACTION;
  DECLARE @actual bigint, @anterior bigint;
  SELECT @actual=COUNT_BIG(*) FROM dbo.ESTADO_PAGO WITH(TABLOCKX,HOLDLOCK);
  SELECT @anterior=COUNT_BIG(*) FROM dbo.MIGRACION_INTEGRIDAD_V45 WITH(TABLOCKX,HOLDLOCK)
    WHERE TABLA=N'ESTADO_PAGO';
  IF @actual<>@anterior+1
    THROW 54705,'El numero de filas no corresponde a una unica alta.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.ESTADO_PAGO WHERE ID_ESTADO_PAGO=N'PENDIENTE'
                AND NULLIF(LTRIM(RTRIM(NOMBRE_ESTADO)),N'') IS NOT NULL)
    THROW 54706,'No existe un estado PENDIENTE valido.',1;
  -- No admitir otras altas ni cambios a registros anteriores.
  IF EXISTS (
    SELECT 1 FROM dbo.ESTADO_PAGO AS r
    LEFT JOIN dbo.MIGRACION_INTEGRIDAD_V45 AS b
      ON b.TABLA=N'ESTADO_PAGO'
     AND b.CLAVE=(SELECT r.ID_ESTADO_PAGO AS ID_ESTADO_PAGO
                  FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES)
    WHERE (b.CLAVE IS NULL AND r.ID_ESTADO_PAGO<>N'PENDIENTE')
       OR (b.CLAVE IS NOT NULL AND b.HUELLA<>HASHBYTES('SHA2_256',
          (SELECT r.ID_ESTADO_PAGO AS ID_ESTADO_PAGO,
                  r.NOMBRE_ESTADO AS NOMBRE_ESTADO
           FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES)))
  ) THROW 54707,'Existen otras altas o cambios no autorizados.',1;
  -- No admitir bajas en el catalogo original.
  IF EXISTS (
    SELECT 1 FROM dbo.MIGRACION_INTEGRIDAD_V45 AS b
    WHERE b.TABLA=N'ESTADO_PAGO'
      AND NOT EXISTS (
        SELECT 1 FROM dbo.ESTADO_PAGO AS r
        WHERE b.CLAVE=(SELECT r.ID_ESTADO_PAGO AS ID_ESTADO_PAGO
                      FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES)
      )
  ) THROW 54708,'Faltan registros de la linea base.',1;

  INSERT dbo.MIGRACION_INTEGRIDAD_V45(TABLA,CLAVE,HUELLA)
  SELECT N'ESTADO_PAGO',
    (SELECT r.ID_ESTADO_PAGO AS ID_ESTADO_PAGO
     FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES),
    HASHBYTES('SHA2_256',
      (SELECT r.ID_ESTADO_PAGO AS ID_ESTADO_PAGO,
              r.NOMBRE_ESTADO AS NOMBRE_ESTADO
       FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES))
  FROM dbo.ESTADO_PAGO AS r
  WHERE r.ID_ESTADO_PAGO=N'PENDIENTE';

  IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION
                WHERE SCRIPT=N'V45_06A_ALTA_ESTADO_PENDIENTE')
    INSERT dbo.CONTROL_MIGRACION(SCRIPT)
    VALUES(N'V45_06A_ALTA_ESTADO_PENDIENTE');
  COMMIT;
  SELECT N'ALTA PENDIENTE REGISTRADA PARA VERIFICACION 07' AS RESULTADO;
END TRY
BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  THROW;
END CATCH;
