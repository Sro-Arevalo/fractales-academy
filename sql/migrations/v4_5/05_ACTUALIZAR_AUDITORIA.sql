 END;');
 CREATE INDEX IX_AUDITORIA_SISTEMA_FECHA_EVENTO ON dbo.AUDITORIA_SISTEMA(FECHA_EVENTO DESC) INCLUDE(ENTIDAD,ACCION,ID_USUARIO_RESPONSABLE,ES_PRUEBA,PROTEGIDO);
 EXEC sys.sp_executesql N'CREATE OR ALTER PROCEDURE dbo.SP_AUDITORIA_PROCESAR_PRUEBAS
 @IDS nvarchar(max),@ID_ADMIN varchar(20),@MOTIVO nvarchar(250),@OPERACION varchar(20),@CONFIRMACION nvarchar(80)
WITH EXECUTE AS OWNER
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 IF ISJSON(@IDS)<>1 OR @OPERACION NOT IN(''DEPURAR'',''ANONIMIZAR'') OR LEN(LTRIM(RTRIM(@MOTIVO)))<5 THROW 54520,''Revisa los eventos, operacion y motivo.'',1;
 DECLARE @eventos table(ID bigint PRIMARY KEY);
 IF EXISTS(SELECT 1 FROM OPENJSON(@IDS) WHERE TRY_CONVERT(bigint,value) IS NULL OR TRY_CONVERT(bigint,value)<1) THROW 54520,''Identificadores de eventos invalidos.'',1;
 INSERT @eventos SELECT CONVERT(bigint,value) FROM OPENJSON(@IDS);
 DECLARE @n int=(SELECT COUNT(*) FROM @eventos),@nombre varchar(120),@politica nvarchar(max),@contenido nvarchar(max);
 IF @n NOT BETWEEN 1 AND 500 OR @CONFIRMACION<>CONCAT(@OPERACION,'' '',@n,'' EVENTOS'') THROW 54520,''Escribe la confirmacion de la cantidad de eventos.'',1;
 BEGIN TRY
  BEGIN TRAN;
  SELECT @nombre=NOMBRE_USUARIO FROM dbo.USUARIO WITH(UPDLOCK,HOLDLOCK) WHERE ID_USUARIO=@ID_ADMIN AND ID_ROL=''ADMIN'' AND ACTIVO=1;
  IF @nombre IS NULL THROW 54520,''Administrador no autorizado.'',1;
  SELECT @politica=(SELECT * FROM dbo.POLITICA_AUDITORIA WITH(UPDLOCK,HOLDLOCK) WHERE ID=1 FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
  IF NOT EXISTS(SELECT 1 FROM dbo.POLITICA_AUDITORIA WHERE ID=1 AND ((@OPERACION=''DEPURAR'' AND PERMITE_DEPURAR=1) OR (@OPERACION=''ANONIMIZAR'' AND PERMITE_ANONIMIZAR=1))) THROW 54520,''La politica actual no autoriza esta operacion.'',1;
  IF (SELECT COUNT(*) FROM dbo.AUDITORIA_SISTEMA a WITH(UPDLOCK,HOLDLOCK) JOIN @eventos e ON e.ID=a.ID WHERE a.ES_PRUEBA=1 AND a.PROTEGIDO=0 AND a.RETENER_HASTA<=SYSUTCDATETIME() AND DATEADD(day,(SELECT DIAS_RETENCION_PRUEBA FROM dbo.POLITICA_AUDITORIA WHERE ID=1),a.FECHA_EVENTO)<=SYSUTCDATETIME())<>@n
   THROW 54520,''La seleccion incluye eventos protegidos, ausentes o dentro de retencion.'',1;
  SELECT @contenido=(SELECT a.* FROM dbo.AUDITORIA_SISTEMA a JOIN @eventos e ON e.ID=a.ID ORDER BY a.ID FOR JSON PATH,INCLUDE_NULL_VALUES);
  INSERT dbo.CONSTANCIA_AUDITORIA(OPERACION,ID_ADMINISTRADOR,NOMBRE_ADMINISTRADOR,CANTIDAD,EVENTOS,HUELLA,MOTIVO,POLITICA)
   VALUES(@OPERACION,@ID_ADMIN,@nombre,@n,@IDS,HASHBYTES(''SHA2_256'',@contenido),@MOTIVO,@politica);
  EXEC sys.sp_set_session_context @key=N''V45_AUDIT_MODO'',@value=@OPERACION;
  IF @OPERACION=''DEPURAR'' DELETE a FROM dbo.AUDITORIA_SISTEMA a JOIN @eventos e ON e.ID=a.ID;
  ELSE UPDATE a SET ID_REGISTRO=''ANONIMIZADO'',ID_USUARIO_RESPONSABLE=''ANONIMIZADO'',NOMBRE_ACTOR=''Contexto ficticio retirado'',DATOS_ANTERIORES=NULL,DATOS_NUEVOS=NULL,MOTIVO=NULL,ANONIMIZADO=1
   FROM dbo.AUDITORIA_SISTEMA a JOIN @eventos e ON e.ID=a.ID;
  EXEC sys.sp_set_session_context @key=N''V45_AUDIT_MODO'',@value=NULL;
  COMMIT;
  SELECT @n CANTIDAD;
 END TRY BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  EXEC sys.sp_set_session_context @key=N''V45_AUDIT_MODO'',@value=NULL;
  THROW;
 END CATCH;
END;
';
