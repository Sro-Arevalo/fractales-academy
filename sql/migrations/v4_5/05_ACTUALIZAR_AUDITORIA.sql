IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WHERE SCRIPT='V45_04_PAPELERA') THROW 54501,'Falta 04.',1;
BEGIN TRY BEGIN TRAN;
IF NOT EXISTS(SELECT 1 FROM dbo.CONTROL_MIGRACION WITH(UPDLOCK,HOLDLOCK) WHERE SCRIPT='V45_05_AUDITORIA')
BEGIN
 ALTER TABLE dbo.AUDITORIA_SISTEMA ADD NOMBRE_ACTOR varchar(120) NULL,ROL_ACTOR varchar(10) NULL,
  ES_PRUEBA bit NOT NULL CONSTRAINT DF_AUDITORIA_SISTEMA_ES_PRUEBA DEFAULT(0) WITH VALUES,
  PROTEGIDO bit NOT NULL CONSTRAINT DF_AUDITORIA_SISTEMA_PROTEGIDO DEFAULT(1) WITH VALUES,
  RETENER_HASTA datetime2(0) NULL,ANONIMIZADO bit NOT NULL CONSTRAINT DF_AUDITORIA_SISTEMA_ANONIMIZADO DEFAULT(0) WITH VALUES;
 DISABLE TRIGGER dbo.TR_AUDITORIA_SISTEMA_PROTEGER ON dbo.AUDITORIA_SISTEMA;
 EXEC(N'UPDATE a SET NOMBRE_ACTOR=u.NOMBRE_USUARIO,ROL_ACTOR=u.ID_ROL FROM dbo.AUDITORIA_SISTEMA a JOIN dbo.USUARIO u ON u.ID_USUARIO=a.ID_USUARIO_RESPONSABLE;');
 ENABLE TRIGGER dbo.TR_AUDITORIA_SISTEMA_PROTEGER ON dbo.AUDITORIA_SISTEMA;
 -- Mantener todos los eventos heredados protegidos; no se reclasifican personas por su nombre/DNI.
 DECLARE @fk sysname,@s nvarchar(max);
 DECLARE f CURSOR LOCAL FAST_FORWARD FOR SELECT name FROM sys.foreign_keys WHERE parent_object_id=OBJECT_ID('dbo.AUDITORIA_SISTEMA') AND referenced_object_id=OBJECT_ID('dbo.USUARIO');
 OPEN f; FETCH NEXT FROM f INTO @fk;
 WHILE @@FETCH_STATUS=0 BEGIN SET @s=N'ALTER TABLE dbo.AUDITORIA_SISTEMA DROP CONSTRAINT '+QUOTENAME(@fk);EXEC sys.sp_executesql @s;FETCH NEXT FROM f INTO @fk;END;
 CLOSE f;DEALLOCATE f;
 CREATE TABLE dbo.POLITICA_AUDITORIA(ID tinyint NOT NULL CONSTRAINT PK_POLITICA_AUDITORIA PRIMARY KEY,
  DIAS_RETENCION_PRUEBA int NOT NULL,PERMITE_DEPURAR bit NOT NULL,PERMITE_ANONIMIZAR bit NOT NULL,
