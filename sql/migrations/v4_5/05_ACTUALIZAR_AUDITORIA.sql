 CREATE TABLE dbo.CONSTANCIA_AUDITORIA(ID bigint IDENTITY NOT NULL CONSTRAINT PK_CONSTANCIA_AUDITORIA PRIMARY KEY,
  FECHA datetime2(0) NOT NULL CONSTRAINT DF_CONSTANCIA_AUDITORIA_FECHA DEFAULT SYSUTCDATETIME(),OPERACION varchar(20) NOT NULL,
  ID_ADMINISTRADOR varchar(20) NOT NULL,NOMBRE_ADMINISTRADOR varchar(120) NOT NULL,CANTIDAD int NOT NULL,
  EVENTOS nvarchar(max) NOT NULL,HUELLA varbinary(32) NOT NULL,MOTIVO nvarchar(250) NOT NULL,POLITICA nvarchar(max) NOT NULL,
  CONSTRAINT CK_CONSTANCIA_AUDITORIA_JSON CHECK(ISJSON(EVENTOS)=1 AND ISJSON(POLITICA)=1));
 EXEC(N'CREATE OR ALTER TRIGGER dbo.TR_CONSTANCIA_AUDITORIA_INMUTABLE ON dbo.CONSTANCIA_AUDITORIA AFTER UPDATE,DELETE AS BEGIN SET NOCOUNT ON;THROW 54522,''La constancia de depuracion se conserva.'',1;END;');
 EXEC(N'CREATE OR ALTER TRIGGER dbo.TR_AUDITORIA_SISTEMA_PROTEGER ON dbo.AUDITORIA_SISTEMA AFTER UPDATE,DELETE AS
 BEGIN SET NOCOUNT ON;
  IF IS_MEMBER(''db_owner'')<>1 OR ISNULL(CONVERT(nvarchar(20),SESSION_CONTEXT(N''V45_AUDIT_MODO'')),'''') NOT IN(''DEPURAR'',''ANONIMIZAR'')
   THROW 54521,''La auditoria solo admite depuracion autorizada mediante el procedimiento del sistema.'',1;
